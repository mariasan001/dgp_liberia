export function buildIconSnippet(lang: CodeLang, icon: IconItem): string {
  if (lang === 'html') {
    return `<i class="ph-thin ${icon.webClass}" aria-hidden="true"></i>`;
  }
  if (lang === 'react') {
    return `import { ${icon.reactName} } from '@phosphor-icons/react';\n\n<${icon.reactName} weight="thin" size={24} aria-hidden />`;
  }
  if (lang === 'vue') {
    return `import { ${icon.vueName} } from '@phosphor-icons/vue';\n\n<${icon.vueName} weight="thin" :size="24" aria-hidden="true" />`;
  }
  return `import '@phosphor-icons/webcomponents/Ph${icon.reactName}';\n\n<${icon.wcTag} weight="thin" size="24" aria-hidden="true"></${icon.wcTag}>`;
}
