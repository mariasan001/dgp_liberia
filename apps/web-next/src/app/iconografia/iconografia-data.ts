export type IconItem = {
  id: string;
  name: string;
  webClass: string;
  reactName: string;
  vueName: string;
  wcTag: string;
  Icon: ComponentType<IconProps>;
};

export type IconCategory = {
  id: string;
  title: string;
  description: string;
  icons: IconItem[];
};

function toKebab(name: string): string {
  return name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .toLowerCase();
}

function item(name: string, IconComp: ComponentType<IconProps>): IconItem {
  const id = toKebab(name);
  return {
    id,
    name,
    webClass: `ph-${id}`,
    reactName: name,
    vueName: `Ph${name}`,
    wcTag: `ph-${id}`,
    Icon: IconComp,
  };
}

